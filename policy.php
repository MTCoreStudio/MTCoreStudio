<?php
// Privacy policies pulled from GitHub (see Admin > Integrations). /privacy/ lists them, /privacy/<app-id> shows one.
require __DIR__ . '/_inc/lib.php';
$base = mt_base();
$id = preg_replace('/[^a-z0-9\-]/', '', strtolower((string)($_GET['app'] ?? '')));

if ($id === '') {
  $list = array_values(array_filter(mt_public_apps(), function ($a) { return !empty($a['pol']); }));
  mt_shell_top(['base' => $base, 'title' => 'Privacy Policies | MT Core Studio', 'desc' => 'Privacy policies for every MT Core Studio Android app.', 'canonical' => $base . 'privacy/', 'page' => 'privacy']);
  echo '<div class="w"><section class="s"><div class="sh"><div><span class="eb">Legal</span><h1 class="h2">Privacy <span class="gt">Policies</span></h1><p>One policy per app, always the latest version.</p></div></div><div class="grid">';
  foreach ($list as $a) echo '<a class="cd gl" href="privacy/' . mt_e($a['id']) . '"><div class="ch"><div><h3>' . mt_e($a['name']) . '</h3><div class="tg">Privacy policy →</div></div></div></a>';
  if (!$list) echo '<div class="gl doc"><p class="mu">No privacy policies are published yet.</p></div>';
  echo '</div></section></div>';
  mt_shell_bottom();
  exit;
}

$store = mt_store();
$app = null;
foreach ($store['apps'] as $a) if (is_array($a) && ($a['id'] ?? '') === $id && empty($a['hid'])) $app = $a;
if (!$app) {
  http_response_code(404);
  mt_shell_top(['base' => $base, 'title' => 'Policy not found | MT Core Studio', 'noindex' => 1, 'page' => 'privacy-404']);
  echo '<div class="w"><section class="s"><div class="gl doc"><h1>Policy not found</h1><p>This app does not exist.</p><p><a class="bt bp" href="privacy/">All policies →</a></p></div></section></div>';
  mt_shell_bottom();
  exit;
}
$name = (string)$app['name'];
$rec = trim((string)($app['policy'] ?? '')) !== '' ? mt_rj('policies/' . $id . '.json', []) : [];
if (!empty($rec['html'])) {                       // 1) policy file synced from GitHub
  $html = $rec['html']; $ts = (int)($rec['changed'] ?? $rec['ts'] ?? time());
  $src = ' · <a href="' . mt_e($rec['web'] ?? '#') . '" target="_blank" rel="noopener">Source on GitHub</a>';
} else {                                          // 2) built-in template (always available)
  require_once __DIR__ . '/_inc/sync.php';
  list($md, $ts) = mt_policy_template($app, (array)$store['set']);
  $html = mt_md($md); $src = '';
}
mt_shell_top(['base' => $base, 'title' => $name . ' Privacy Policy | MT Core Studio', 'desc' => 'Privacy policy for the ' . $name . ' Android app by MT Core Studio.', 'canonical' => $base . 'privacy/' . $id,
  'noindex' => (($app['st'] ?? '') === 'Draft') ? 1 : 0, 'page' => 'privacy:' . $id]);
echo '<div class="w"><section class="s"><nav class="crumb"><a href="privacy/">← All policies</a></nav><article class="gl doc"><header class="doc-h"><h1>' . mt_e($name) . ' — Privacy Policy</h1><div class="tg">Last updated ' . mt_e(gmdate('F j, Y', $ts)) . $src . '</div></header><div class="doc-b">';
echo $html;      // generated by us or sanitised when synced
echo '</div></article></section></div>';
mt_shell_bottom();
